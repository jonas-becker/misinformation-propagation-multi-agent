#!/usr/bin/env python3
"""
make_details_table.py - Render the experimental-details appendix tables from
configs/experiment_config.json plus run metadata found under out/ and out/results/.

Nothing in the tables is typed by hand: every cell is read from the config file
(which the runners also read) or from run_metadata / run_info files written by
the runs themselves. Fields ending in `_short` in the config hold the wording of
the compact tables; the long fields feed the full table.

Outputs:
  out/appendix/model_settings.tex / .csv        one row per model: checkpoint, serving, context, sampling, token limits
  out/appendix/experimental_details.tex / .csv  ten one-line rows: data, MINT, runners, protocols, scoring, statistics
  out/appendix/run_inventory.tex / .csv         every run with model, seed, tokens, git commit (supplementary)
  out/appendix/experimental_details_full.tex    the long table (only with --full)
"""

from __future__ import annotations

import argparse
import glob
import json
import sys
from pathlib import Path
from typing import List, Tuple

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from scripts.common import write_csv, write_latex_table  # noqa: E402

Row = Tuple[str, str, str]


def _s(d: dict, key: str) -> str:
    """Short wording if the config has it, else the long field."""
    return str(d.get(f"{key}_short") or d.get(key) or "")


def _fmt_p(v) -> str:
    return "--" if v is None else f"{float(v):.1f}"


def _rows_models(cfg: dict) -> List[List[str]]:
    rows = []
    for m in cfg["models"]:
        serving = _s(m, "served_with")  # "vLLM 0.19.0, tensor parallel 2, bf16"
        tp = next((tok.split()[-1] for tok in serving.split(",") if "tensor parallel" in tok), "--")
        parser = m.get("reasoning_parser_short") or ""
        parser = parser.split(" in the ")[0].replace("reasoning parser ", "") if parser and not parser.startswith("no ") else "--"
        rows.append([m["display"], f"{m['hf_id']} ({m['revision'][:8]})", tp, parser, f"{m['max_model_len']:,}",
                     f"{_fmt_p(m['default_temperature'])} / {_fmt_p(m['default_top_p'])}",
                     f"{m['max_tokens_single']:,} / {m['max_tokens_debate']:,}"])
    return rows


def _rows_setup(cfg: dict) -> List[List[str]]:
    ds = cfg["datasets"]
    data = "; ".join(f"{d['short_name']} (n = {d['n']}, {d['answer_type_short']})" for k, d in ds.items() if not k.startswith("_"))
    mg, gp = cfg["mint_generation"], cfg["mint_generation"]["generation_params"]
    vc = mg["verified_counts"]
    sa, sc, db = cfg["single_agent"], cfg["self_consistency"], cfg["debate"]
    ex = db.get("exposure_runs") or {}
    return [
        ["Datasets", f"{data}; {ds.get('_sampling_short', '')}"],
        ["MINT passages", f"generated by {_s(mg, 'generator')} (T {gp['temperature']}, top-p {gp['top_p']}); {_s(mg, 'passages')}, "
                          f"{mg['n_passages']:,} passages; controls: {_s(mg, 'controls')}"],
        ["Verified subset", f"{_s(mg, 'validation')}: CWQ {vc['cwq']}, ETHICS {vc['ethics']}, WinoGrande {vc['winogrande']} questions; "
                            "used for all debates and mSC runs with k >= 1"],
        ["Single agent", f"T {sa['temperature']}, top-p {_fmt_p(sa['top_p'])}, max {sa['max_tokens_reasoning_models']:,} tokens; {_s(sa, 'seed')}"],
        ["Self-consistency", f"mSC: {sc['num_samples_msc']} samples at T {sc['msc_temperature']}, top-p {sc['msc_top_p']} (MALLM single-agent system prompt with the "
                             f"debate's task instruction and input)"
                             + (f"; Llama-3.3 mSC repeated at the debate's T {sc['msc_matched_temperature']}, top-p "
                                f"{sc['msc_matched_top_p']} as a sensitivity check" if sc.get("msc_matched_temperature") else "")
                             + f"; SC15: {sc['num_samples']} samples at T {sc['temperature']}, top-p {sc['top_p']}; {_s(sc, 'aggregation')}"],
        ["Debate", f"{_s(db, 'framework')}; {db['num_agents']} agents ({db['num_agents_exp3']} in the composition sweep), vote after turn "
                   f"{db['vote_turn']}, at most {db['max_turns']} turns; sampling at the server default of each model; "
                   f"{_s(db, 'passage_sharing')}; {_s(db, 'seeds')}"],
        ["Protocols", f"{_s(db['protocols'], 'voting')}; {_s(db['protocols'], 'consensus')}"],
        ["Mitigations", _s(ex, "mitigations")],
        ["Scoring", _s(cfg["answer_extraction"], "setup")],
        ["Statistics", _s(cfg["statistics"], "setup")],
    ]


def _rows_full(cfg: dict) -> List[Row]:
    rows: List[Row] = []
    for m in cfg["models"]:
        rows.append(("Model", m["display"], f"{m['hf_id']} (revision: {m['revision']}); {m['served_with']}; "
                                            f"max_model_len {m['max_model_len']}; reasoning parser: {m['reasoning_parser'] or 'none'}"
                                            + (f"; default sampling: {m['effective_default_sampling']}" if m.get("effective_default_sampling") else "")
                                            + (f"; NOTE: {m['sampling_note']}" if m.get("sampling_note") else "")))
    for key, d in cfg["datasets"].items():
        if key.startswith("_"):
            continue
        rows.append(("Dataset", d["name"], f"{d['hf_id']}, {d['split']}, n={d['n']}; {d['answer_type']}; sampling: {d['sampling']}"))
    mg = cfg["mint_generation"]
    rows.append(("MINT generation", "generator", mg["generator"]))
    rows.append(("MINT generation", "parameters", ", ".join(f"{k}={v}" for k, v in mg["generation_params"].items())))
    rows.append(("MINT generation", "pipeline", mg["pipeline"]))
    rows.append(("MINT generation", "categories", ", ".join(mg["categories"]) + f" ({mg['n_passages']} passages)"))
    rows.append(("MINT generation", "irrelevant-true control", mg["irrelevant_true"]))
    rows.append(("MINT generation", "validation", mg["validation"]))
    sa = cfg["single_agent"]
    rows.append(("Single agent", "runner / prompt", f"{sa['runner']}; {sa['prompt']}"))
    rows.append(("Single agent", "sampling", f"temperature {sa['temperature']}, top-p {sa['top_p']} ({sa.get('top_p_note', '')}), max tokens "
                                             f"{sa['max_tokens']} (reasoning models: {sa['max_tokens_reasoning_models']}); seeds: {sa['seed']}"))
    rows.append(("Single agent", "chat template", sa["chat_template"]))
    sc = cfg["self_consistency"]
    rows.append(("Self-consistency", "samples", f"{sc['num_samples']} (SC15), {sc['num_samples_msc']} (mSC); {sc.get('sampling_note', '')}; "
                                                f"seed {sc['seed']}"))
    rows.append(("Self-consistency", "aggregation", sc["aggregation"]))
    db = cfg["debate"]
    rows.append(("Debate", "framework", db["framework"]))
    rows.append(("Debate", "agents / turns", f"{db['num_agents']} agents ({db['num_agents_exp3']} in the composition sweep), max {db['max_turns']} turns, "
                                             f"vote at turn {db['vote_turn']}, visible turns in memory {db['visible_turns_in_memory']}, "
                                             f"chain-of-thought {db['use_chain_of_thought']}"))
    rows.append(("Debate", "generation", f"max tokens {db['max_tokens']} (reasoning models: {db['max_tokens_reasoning_models']}); temperature: {db['temperature']}"))
    if db.get("composition_sweep_fill"):
        rows.append(("Debate", "composition sweep (exp3)", db["composition_sweep_fill"]))
    rows.append(("Debate", "agent order", db["agent_order"]))
    rows.append(("Debate", "voting protocol", db["protocols"]["voting"]))
    rows.append(("Debate", "consensus protocol", db["protocols"]["consensus"]))
    rows.append(("Debate", "passage sharing (k>1)", db["passage_sharing"]))
    rows.append(("Debate", "seeds", db["seed"]))
    for key, val in (db.get("exposure_runs") or {}).items():
        if key.endswith("_short"):
            continue
        rows.append(("Exposure runs", key.replace("_", " "), str(val)))
    ex = cfg["answer_extraction"]
    rows.append(("Answer extraction", "method", f"{ex['module']}: {ex['rule']}"))
    rows.append(("Answer extraction", "handling of failures", ex["handling"]))
    rows.append(("Answer extraction", "free-form scoring", ex["free_form"]))
    st = cfg["statistics"]
    rows.append(("Statistics", "confidence intervals", st["ci"]))
    rows.append(("Statistics", "tests", st["test"]))
    rows.append(("Statistics", "seeds", st["seeds"]))
    return rows


def _rows_run_inventory() -> List[Row]:
    rows: List[Row] = []
    for p in sorted(glob.glob(str(REPO_ROOT / "out" / "*" / "runs" / "*" / "run_info.env"))):
        kv = {}
        for line in Path(p).read_text(encoding="utf-8", errors="ignore").splitlines():
            if "=" in line:
                k, v = line.split("=", 1)
                kv[k.strip()] = v.strip()
        rows.append(("exp2", kv.get("EXP2_RUN_ID", Path(p).parent.name),
                     f"model {kv.get('MODEL_NAME', '?')}, datasets {kv.get('DATASET', '?')}, started {kv.get('started_at', '?')}, "
                     f"finished {kv.get('finished_at', '?')}, Slurm job {kv.get('SLURM_JOB_ID', '?')}"))
    for p in sorted(glob.glob(str(REPO_ROOT / "out" / "*" / "*" / "run_metadata_*.json"))):
        try:
            meta = json.loads(Path(p).read_text(encoding="utf-8"))
        except Exception:
            continue
        a = meta.get("args", {})
        rows.append(("runner", Path(p).parent.name,
                     f"{meta.get('timestamp_utc', '?')}; model {meta.get('model_name') or a.get('model_name', '?')}; "
                     f"k={a.get('k', '?')}, n={a.get('num_agents', a.get('num_samples', '?'))}, seed={a.get('seed', '?')}, "
                     f"max_tokens={meta.get('max_tokens', a.get('max_tokens', '?'))}, git {str(meta.get('git_commit') or '?')[:8]}"))
    return rows


def _dedupe_sections(rows: List[Row]) -> List[List[str]]:
    out, last = [], None
    for sec, item, val in rows:
        out.append([sec if sec != last else "", item, val])
        last = sec
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default=str(REPO_ROOT / "configs" / "experiment_config.json"))
    ap.add_argument("--out_dir", default=str(REPO_ROOT / "out" / "appendix"))
    ap.add_argument("--full", action="store_true", help="also write the long table (experimental_details_full.tex)")
    args = ap.parse_args()
    cfg = json.loads(Path(args.config).read_text(encoding="utf-8"))
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    models = _rows_models(cfg)
    header = ["Model", "Checkpoint (revision)", "TP", "Reasoning parser", "Context", "T / top-p", "Max new tokens"]
    vllm = cfg["models"][0].get("served_with_short", "vLLM").split(",")[0]
    sa, sc = cfg["single_agent"], cfg["self_consistency"]
    write_csv(out / "model_settings.csv", [dict(zip(header, r)) for r in models])
    write_latex_table(out / "model_settings.tex", header, models,
                      caption=f"Models. All models are served with {vllm} in bf16 (TP = tensor parallel size). T / top-p is the server "
                              "default that applies to the debates, which send no sampling parameters (Llama: the model's generation "
                              f"config; GLM and GPT-OSS: vLLM defaults). Explicit settings elsewhere: single agent T {sa['temperature']} / "
                              f"top-p {_fmt_p(sa['top_p'])}, mSC T {_fmt_p(sc['msc_temperature'])} / top-p {_fmt_p(sc['msc_top_p'])}, "
                              f"SC15 T {sc['temperature']} / top-p {sc['top_p']}. Max new tokens: single agent / debate turn.",
                      label="tab:model_settings", col_spec="llclrcc", font="footnotesize", wide=True)
    print(f"wrote {out / 'model_settings.tex'} ({len(models)} rows)")

    setup = _rows_setup(cfg)
    write_csv(out / "experimental_details.csv", [{"item": r[0], "setting": r[1]} for r in setup])
    write_latex_table(out / "experimental_details.tex", ["Item", "Setting"], setup,
                      caption="Experimental setup. Generated from the configuration file the runners read "
                              "(configs/experiment\\_config.json, released with the code, together with a per-run inventory); "
                              "model settings in Table~\\ref{tab:model_settings}.",
                      label="tab:experimental_details", col_spec="p{2.6cm}p{12.0cm}", font="footnotesize", wide=True)
    todo = sum(1 for r in setup if "TODO_USER" in r[1])
    print(f"wrote {out / 'experimental_details.tex'} ({len(setup)} rows, {todo} TODO_USER entries)")

    inv = _rows_run_inventory()
    write_csv(out / "run_inventory.csv", [{"experiment": r[0], "run": r[1], "details": r[2]} for r in inv])
    write_latex_table(out / "run_inventory.tex", ["Exp.", "Run", "Details"], _dedupe_sections(inv),
                      caption="Run inventory generated from the run metadata written by the runners (timestamp, model, "
                              "exposure k, agents or samples, seed, max tokens, git commit).",
                      label="tab:run_inventory", col_spec="p{1.5cm}p{3.3cm}p{9.8cm}", font="scriptsize", wide=True)
    print(f"wrote {out / 'run_inventory.tex'} ({len(inv)} runs)")

    if args.full:
        full = _rows_full(cfg)
        write_csv(out / "experimental_details_full.csv", [{"section": r[0], "item": r[1], "value": r[2]} for r in full])
        write_latex_table(out / "experimental_details_full.tex", ["Section", "Item", "Value"], _dedupe_sections(full),
                          caption="Experimental details, long form. All entries are generated from the configuration file that "
                                  "the runners read; entries marked TODO\\_USER were not recoverable from the repository.",
                          label="tab:experimental_details_full", col_spec="p{2.0cm}p{2.4cm}p{10.2cm}", font="scriptsize", wide=True)
        print(f"wrote {out / 'experimental_details_full.tex'} ({len(full)} rows)")


if __name__ == "__main__":
    main()
