#!/usr/bin/env python3
"""
make_verified_subsets.py - Write the judge-verified question subsets as plain id lists
(configs/subsets/verified_<dataset>.txt), so that runs on passage sets without validation flags
(e.g. the relevant-true control set in controls/relevant_true) can be restricted to the same
questions via `--mint_ids_file configs/subsets/verified_{dataset}.txt` (exp_exposure.py, exp_msc.py).

The rule is the one of the analyses (scripts/common.py::verified_questions, criterion per dataset from
configs/experiment_config.json `mint_generation.verification_criterion`): both judges on Q1 and Q2 for
CWQ and ETHICS, both judges on Q2 for WinoGrande (its fictional scenarios make Q1 ill-posed).
--data_dir selects the flags (default: the release; MINT_dataset_v1.2/rejudge_q1_plausibility for the
re-judged WinoGrande flags used by the sampling-matched mSC and skepticism runs).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from mint_data import canonical_dataset  # noqa: E402
from scripts.common import _JUDGE_KEYS, verification_criterion, verified_questions  # noqa: E402

DEFAULT_OUT_DIR = REPO_ROOT / "configs" / "subsets"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data_dir", default=None, help="passage flags to use (default: MINT_dataset_v1.2)")
    ap.add_argument("--out_dir", default=str(DEFAULT_OUT_DIR))
    ap.add_argument("--datasets", default="cwq,ethics,winogrande")
    ap.add_argument("--category", default="false_fact")
    ap.add_argument("--criterion", default=None, help="override the per-dataset rule (both_q1q2, both_q2, ...)")
    args = ap.parse_args()
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    data_dir = Path(args.data_dir) if args.data_dir else None
    for ds in [d.strip() for d in args.datasets.split(",") if d.strip()]:
        ds = canonical_dataset(ds)
        crit = args.criterion or verification_criterion(ds)
        ids = sorted(verified_questions(ds, args.category, criterion=crit, data_dir=data_dir))
        path = out_dir / f"verified_{ds}.txt"
        with open(path, "w", encoding="utf-8") as f:
            f.write(f"# {ds}: {len(ids)} questions whose {args.category} passage is judge-verified ({crit}; judges "
                    f"{', '.join(_JUDGE_KEYS)}; flags from {data_dir or 'MINT_dataset_v1.2'}); "
                    f"generated by scripts/make_verified_subsets.py\n")
            f.write("\n".join(ids) + "\n")
        print(f"{ds}: {len(ids)} ids -> {path}")


if __name__ == "__main__":
    main()
