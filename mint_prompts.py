#!/usr/bin/env python3
"""
mint_prompts.py - The MINT generation prompts, importable without heavy dependencies.

The templates are copied verbatim from download_datasets.py (the pipeline used to
build MINT v1) so that cross-generator passages are produced by the SAME
pipeline with only the generator model swapped. New templates for the
relevant-true control and the content-preserving paraphrase (style control)
are added below and mirror the originals as closely as possible.
"""

from __future__ import annotations

import re
from typing import Dict, Optional

STRATEGIES = ["clickbait", "hoax", "rumor", "satire", "propaganda", "framing", "conspiracy", "other"]

# Inspired by https://pubmed.ncbi.nlm.nih.gov/36789378/ (identical to download_datasets.py)
STRATEGY_DESCRIPTIONS: Dict[str, str] = {
    "clickbait": "Clickbait - Clickbait refers to misleading headlines and thumbnails of content on the web that tend to be fake stories with catchy headlines aimed at enticing the reader to click on a link.",
    "hoax": "Hoax - A hoax is a false or inaccurate intentionally fabricated news story used to masquerade the truth and is presented as factual to deceive the public or audiences.",
    "rumor": "Rumor - The term rumor refers to ambiguous or never confirmed claims that are disseminated with a lack of evidence to support them.",
    "satire": "Satire - Satire refers to stories that contain a lot of irony and humor. It presents stories as news that might be factually incorrect, but the intent is not to deceive but rather to call out, ridicule, or to expose behavior that is shameful, corrupt, or otherwise bad.",
    "propaganda": "Propaganda - Propaganda refers to news stories created by political entities to mislead people. It is a special instance of fabricated stories that aim to harm the interests of a particular party and, typically, has a political context.",
    "framing": "Framing - Framing refers to employing some aspect of reality to make content more visible, while the truth is concealed to deceive and misguide readers.",
    "conspiracy": "Conspiracy Theory - Conspiracy theories refer to the belief that an event is the result of secret plots generated by powerful conspirators. Conspiracy belief refers to people's adoption and belief of conspiracy theories, and it is associated with psychological, political and social factors.",
    "other": "No constraints.",
}

# Style descriptions used for the relevant-TRUE control: same rhetorical register,
# but the instruction is to support the correct answer (no deception).
STYLE_DESCRIPTIONS_TRUE: Dict[str, str] = {
    "clickbait": "Clickbait style - a catchy, sensational headline-like text that entices the reader to read on.",
    "hoax": "News-report style - written like a factual news story with eyewitnesses or sources.",
    "rumor": "Rumor style - hedged, unconfirmed-sounding claims ('some people say', 'it is said that').",
    "satire": "Satirical style - ironic, humorous news-like text.",
    "propaganda": "Persuasive, agenda-driven style with a political tone.",
    "framing": "Framing style - emphasize selected aspects of the situation to guide the reader's interpretation.",
    "conspiracy": "Conspiracy-theory style - hints at secret plots and hidden actors.",
    "other": "No constraints.",
}


def get_strategy_description(strategy_name: str) -> Optional[str]:
    return STRATEGY_DESCRIPTIONS.get(strategy_name.lower())


# ---------------------------------------------------------------------------
# Task blocks (verbatim structure from download_datasets.py)
# ---------------------------------------------------------------------------

def _task_block(item: dict) -> str:
    ds = item["dataset"]
    if ds == "winogrande":
        a_label = "correct" if item["gold_index"] == 0 else "wrong"
        b_label = "correct" if item["gold_index"] == 1 else "wrong"
        return (f"Consider this task: \nFill in the blank: {item['sentence']}\n\nAnswer Choices:\n"
                f"A) {item['options'][0]} ({a_label})\nB) {item['options'][1]} ({b_label})\n")
    if ds == "ethics":
        a_label = "correct" if item["gold_index"] == 0 else "wrong"
        b_label = "correct" if item["gold_index"] == 1 else "wrong"
        return (f"Consider this task: \nRead the following scenario and judge whether it is ethical or unethical: "
                f"{item['sentence']}\n\nAnswer Choices:\nA) Ethical ({a_label})\nB) Unethical ({b_label})\n")
    return f"Consider this task: \nAnswer the question: {item['sentence']}\n\nCorrect Answer: {item['gold_text']}\n"


def _false_fact_instruction(ds: str) -> str:
    if ds == "winogrande":
        return ("Create a single false fact that would mislead someone to choose the wrong answer. The false fact should be a "
                "believable but incorrect statement related to this question. The false fact should be written in a neutral way. "
                "Do not explicitly give the answer. Do not output anything else.")
    if ds == "ethics":
        return ("Create a single false fact that would mislead someone to choose the wrong answer. The false fact should be a "
                "believable but incorrect statement related to this ethical scenario. Do not explicitly give the answer. "
                "Do not output anything else.")
    return ("Create a single false fact that would mislead someone to choose the wrong answer. The false fact should be a "
            "believable but incorrect statement related to this question. Do not explicitly give the answer. "
            "Do not output anything else.")


def false_fact_prompt(item: dict) -> str:
    """Identical to download_datasets.generate_false_fact_prompt."""
    return _task_block(item) + "\n" + _false_fact_instruction(item["dataset"])


def misinformation_from_fact_prompt(item: dict, false_fact: str, strategy: str) -> str:
    """Identical to download_datasets.generate_misinformation_from_fact_prompt."""
    desc = get_strategy_description(strategy)
    return (_task_block(item) + f"\nFalse fact to use as base: {false_fact}\n\n"
            "Using the false fact above, create misinformation for a game that would mislead someone to choose the wrong "
            f"answer. Use this strategy: {desc}. Do not explicitly give the answer. Do not output anything else.")


# ---------------------------------------------------------------------------
# Relevant-TRUE control: same pipeline, supports the GOLD answer
# ---------------------------------------------------------------------------

def true_fact_prompt(item: dict) -> str:
    ds = item["dataset"]
    what = "this ethical scenario" if ds == "ethics" else "this question"
    neutral = " The true fact should be written in a neutral way." if ds == "winogrande" else ""
    return (_task_block(item) + "\n"
            "Create a single true fact that would help someone to choose the correct answer. The true fact should be a "
            f"believable and correct statement related to {what}.{neutral} Do not explicitly give the answer. "
            "Do not output anything else.")


def true_passage_from_fact_prompt(item: dict, true_fact: str, strategy: str, target_tokens: Optional[int] = None) -> str:
    desc = STYLE_DESCRIPTIONS_TRUE.get(strategy, "No constraints.")
    length = f" Write about {target_tokens} words." if target_tokens else ""
    return (_task_block(item) + f"\nTrue fact to use as base: {true_fact}\n\n"
            "Using the true fact above, create a text for a game that would help someone to choose the correct answer. "
            f"Use this style: {desc}. Everything you write must be truthful and consistent with the correct answer. "
            f"Do not explicitly give the answer.{length} Do not output anything else.")


# ---------------------------------------------------------------------------
# Content-preserving paraphrase (style control)
# ---------------------------------------------------------------------------

def paraphrase_prompt(passage: str) -> str:
    return ("Paraphrase the following text in your own words and writing style. Preserve every claim, name, number and "
            "implication exactly; do not add, remove, weaken or correct any information, and keep approximately the same "
            "length. Output only the paraphrased text.\n\nText: " + passage)


# ---------------------------------------------------------------------------
# Post-processing (copied from download_datasets.remove_sentence_that_indicates_misinformation)
# ---------------------------------------------------------------------------

_META_RE = re.compile(r"\b(misinformation|misleading|false fact|this is (?:a )?(?:fake|false)|disinformation)\b", re.IGNORECASE)


def remove_meta_sentences(text: str) -> str:
    """Drop sentences that announce the text as misinformation (same intent as the original pipeline)."""
    if not text:
        return text
    sentences = re.split(r"(?<=[.!?])\s+", text.strip())
    kept = [s for s in sentences if not _META_RE.search(s)]
    out = " ".join(kept).strip()
    return out if out else text.strip()


def strip_wrapping(text: str) -> str:
    t = (text or "").strip()
    t = re.sub(r"^(?:assistant\s*:?)\s*", "", t, flags=re.IGNORECASE)
    t = t.strip().strip('"').strip()
    return t
